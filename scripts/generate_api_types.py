"""Generate the frontend's API types, frontend/src/api/schema.ts, from FastAPI's API description.

openapi-typescript (pinned below, run with pnpm dlx, so it needs Node and the network) turns the description into
TypeScript. The file's first line is the description's fingerprint, which tests/api/test_api_types.py checks without
Node, so a test fails when the API changes and the types weren't regenerated. The build carries the fingerprint too
(frontend/vite.config.ts), and the app refuses to serve a build made for a different API.

Run: uv run python -m scripts.generate_api_types
"""

import json
import subprocess
import tempfile
from pathlib import Path
from typing import Any

from chessllm.api.app import create_app
from chessllm.api.routes.pages import api_fingerprint

OPENAPI_TYPESCRIPT = "openapi-typescript@7.13.0"
SCHEMA_FILE = Path(__file__).parent.parent / "frontend" / "src" / "api" / "schema.ts"


def api_description() -> dict[str, Any]:
    """The OpenAPI description FastAPI serves at /openapi.json. No game is played, so no LLM player is built."""
    return create_app(lambda settings, color: None).openapi()  # type: ignore[arg-type, return-value]


def schema_header(description: dict[str, Any]) -> str:
    """The first line of schema.ts. The frontend's build carries its fingerprint, and the app refuses a build whose
    fingerprint isn't its own."""
    return (
        "// Generated by scripts/generate_api_types.py from the API description with sha256 "
        f"{api_fingerprint(description)}"
    )


def main() -> None:
    description = api_description()
    with tempfile.TemporaryDirectory() as directory:
        openapi_file = Path(directory) / "openapi.json"
        openapi_file.write_text(json.dumps(description, indent=2), encoding="utf-8")
        types = subprocess.run(
            ["pnpm", "dlx", OPENAPI_TYPESCRIPT, str(openapi_file)], check=True, capture_output=True, text=True
        ).stdout
    SCHEMA_FILE.parent.mkdir(parents=True, exist_ok=True)
    SCHEMA_FILE.write_text(f"{schema_header(description)}\n{types}", encoding="utf-8")
    print(f"Wrote {SCHEMA_FILE}")


if __name__ == "__main__":
    main()
